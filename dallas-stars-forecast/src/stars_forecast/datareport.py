"""Generates docs/data-report.md from the collected data and validation evidence.

The report is regenerated by `python -m stars_forecast data-report`. It contains no
simulated forecasts by design: it describes and validates the observed data only.
"""
from __future__ import annotations

import json
from datetime import datetime, timezone
from typing import Any

import pandas as pd

from .paths import DOCS, PROCESSED, RAW, QA, rel


def _md_table(df: pd.DataFrame, cols: list[str] | None = None, index: bool = False) -> str:
    if cols:
        df = df[cols]
    return df.to_markdown(index=index)


def _manifest() -> dict[str, Any]:
    path = RAW / "source_manifest.json"
    return json.loads(path.read_text()) if path.exists() else {"files": [], "n_files": 0}


def write_data_report() -> str:
    """Build docs/data-report.md and return its path."""
    totals26 = pd.read_csv(PROCESSED / "team_totals_dal_2025_26.csv").iloc[0]
    totals25 = pd.read_csv(PROCESSED / "team_totals_dal_2024_25.csv").iloc[0]
    log26 = pd.read_csv(PROCESSED / "game_log_dal_2025_26.csv")
    log25 = pd.read_csv(PROCESSED / "game_log_dal_2024_25.csv")
    skaters = pd.read_csv(PROCESSED / "skaters_dal_2025_26.csv")
    goalies = pd.read_csv(PROCESSED / "goalies_dal_2025_26.csv")
    standings = pd.read_csv(PROCESSED / "central_standings_2021_2026.csv")
    roster = pd.read_csv(PROCESSED / "roster_dal_2026_27.csv")
    arrivals = pd.read_csv(PROCESSED / "arrivals_dal_2026_27_prior_season.csv")
    validation = json.loads((QA / "data-validation.json").read_text())
    hr26 = json.loads((PROCESSED / "hr_crosscheck_2025_26.json").read_text())
    hr25 = json.loads((PROCESSED / "hr_crosscheck_2024_25.json").read_text())
    manifest = _manifest()

    retrieved = sorted({f["retrieved_utc"][:10] for f in manifest["files"]})
    checksum_example = next((f["sha256"] for f in manifest["files"] if f["dataset"] == "B"), "")

    # ---- reconciliation numbers -------------------------------------------------
    def rec(log: pd.DataFrame, totals: pd.Series) -> dict[str, Any]:
        wins = int((log["result"] == "W").sum())
        otl = int(((log["result"] == "L") & log["finish"].isin(["OT", "SO"])).sum())
        regl = int(((log["result"] == "L") & (log["finish"] == "REG")).sum())
        return {
            "official_gf": int(totals["goals_for"]), "log_gf_final": int(log["goals_for_final_hockey"].sum()),
            "log_gf_displayed": int(log["goals_for_displayed"].sum()),
            "log_gf_reg": int(log["goals_for_reg"].sum()),
            "official_ga": int(totals["goals_against"]), "log_ga_final": int(log["goals_against_final_hockey"].sum()),
            "log_ga_displayed": int(log["goals_against_displayed"].sum()),
            "log_ga_reg": int(log["goals_against_reg"].sum()),
            "official_points": int(totals["points"]), "log_points": 2 * wins + otl,
            "wins": wins, "regl": regl, "otl": otl,
            "official_games": int(totals["gp"]), "log_games": len(log),
            "ot_games": int((log["finish"] == "OT").sum()),
            "so_games": int((log["finish"] == "SO").sum()),
            "tied_after_reg": int((log["goals_for_reg"] == log["goals_against_reg"]).sum()),
        }

    r26, r25 = rec(log26, totals26), rec(log25, totals25)

    L: list[str] = []
    a = L.append
    a("# Dallas Stars 2026-27 Forecasting Project — Data Report\n")
    a(f"_Generated {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')} by "
      f"`python -m stars_forecast data-report`._\n")
    a("This report describes and validates the observed datasets used to fit the forecast "
      "model. It contains **no simulated results**; model outputs are reported separately in "
      "`outputs/results-summary.md` and the final academic report.\n")

    # ---------------------------------------------------------------- summary
    a("## 1. What this report covers\n")
    a("| Item | Value |")
    a("|---|---|")
    a(f"| Model-fitting data cutoff | End of the 2025-26 regular season |")
    a(f"| Datasets collected | A-G (team totals, game log, skaters, goalies, 2024-25 season, "
      f"Central standings, 2026-27 roster) |")
    a(f"| Source files cached under `data/raw/` | {manifest['n_files']} |")
    a(f"| Retrieval dates | {', '.join(retrieved)} |")
    a(f"| Automated data checks | {validation['n_passed']}/{validation['n_checks']} passed |")
    a(f"| 2026-27 game results used | None (verified by an automated check) |")
    a(f"| Example checksum (`game_log_dal_2025_26.csv` source) | `{checksum_example[:32]}...` |\n")

    a("## 2. Sources and provenance\n")
    a("Every download is cached unchanged under `data/raw/`, organised by source and season. "
      "The manifest `data/raw/source_manifest.json` records the dataset, file, actual source "
      "URL, retrieval timestamp, row/file size, SHA-256 checksum and whether the file came "
      "from the cache.\n")
    a("| Dataset | Primary source | Endpoint / page | Cached file |")
    a("|---|---|---|---|")
    a(f"| A — Dallas 2025-26 team totals | NHL.com official stats API | "
      f"`api.nhle.com/stats/rest/en/team/summary` (seasonId=20252026, gameTypeId=2) | "
      f"`data/raw/nhl/team_summary/team_summary_20252026.json` |")
    a(f"| B — Dallas 2025-26 game log | NHL.com official gamecenter API | "
      f"`api-web.nhle.com/v1/club-schedule-season/DAL/20252026` + "
      f"`/v1/gamecenter/<gameId>/right-rail` | `data/raw/nhl/schedule/`, "
      f"`data/raw/nhl/right_rail/` |")
    a(f"| C — Dallas 2025-26 skaters | NHL.com official stats API | "
      f"`.../skater/summary` (teamAbbrevs=\"DAL\") | `data/raw/nhl/skaters/` |")
    a(f"| D — Dallas 2025-26 goalies | NHL.com official stats API | "
      f"`.../goalie/summary` (teamAbbrevs=\"DAL\") | `data/raw/nhl/goalies/` |")
    a(f"| E — Dallas 2024-25 totals + game log | NHL.com official APIs | same endpoints, "
      f"seasonId=20242025 | `data/raw/nhl/...` |")
    a(f"| F — Central Division standings 2021-22 to 2025-26 | NHL.com official standings API | "
      f"`api-web.nhle.com/v1/standings/<final regular-season date>` | "
      f"`data/raw/nhl/standings/` |")
    a(f"| G — Initial 2026-27 Dallas roster | NHL.com official roster API | "
      f"`api-web.nhle.com/v1/roster/DAL/20262027` | `data/raw/nhl/roster/` |")
    a(f"| Cross-check — Dallas game logs | Hockey-Reference | "
      f"`hockey-reference.com/teams/DAL/2026_gamelog.html`, `.../2025_gamelog.html` | "
      f"`data/raw/hockey-reference/` |")
    a("")
    a("**Substitute-source note.** The proposal named Hockey-Reference as the game-log source. "
      "The official NHL gamecenter API was used as the primary game-log source because it "
      "carries period-by-period scoring, which is what makes overtime and shootout accounting "
      "verifiable. Hockey-Reference was then collected as an independent cross-check, and the "
      "cross-check succeeded for both seasons (section 6). This is a source substitution, not a "
      "missing cross-check.\n")
    a("The 2026-27 roster announcement page cited in the proposal was also fetched and cached "
      "(`data/raw/nhl/news/stars_roster_announcement_2026_27.html`, result recorded in "
      "`data/processed/roster_announcement_probe.json`). The roster CSV itself comes from the "
      "official roster endpoint, which is a dated snapshot: it is captured on "
      f"{roster['roster_snapshot_utc'].iloc[0]} and is **not** an opening-night lineup claim.\n")

    # ---------------------------------------------------------------- conventions
    a("## 3. Goal conventions (the most important definition in this project)\n")
    a("Three different quantities are routinely called \"goals\" in hockey data. The datasets "
      "keep all three separately, and nothing is silently converted:\n")
    a("| Convention | Column suffix | Meaning | 2025-26 Dallas value |")
    a("|---|---|---|---|")
    a(f"| Regulation goals | `_reg` | goals scored at 60 minutes | "
      f"{r26['log_gf_reg']} for / {r26['log_ga_reg']} against |")
    a(f"| Final hockey goals | `_final_hockey` | regulation + overtime goals | "
      f"{r26['log_gf_final']} for / {r26['log_ga_final']} against |")
    a(f"| Displayed score | `_displayed` | final hockey + shootout decision increment | "
      f"{r26['log_gf_displayed']} for / {r26['log_ga_displayed']} against |")
    a("")
    a(f"The official NHL team totals for 2025-26 are **{r26['official_gf']} goals for and "
      f"{r26['official_ga']} against**. Those numbers match the *final hockey* convention "
      f"exactly, and differ from the shootout-inclusive displayed sum by "
      f"{r26['log_gf_displayed'] - r26['official_gf']} goals. The shootout increment is "
      "therefore excluded from the official totals and from the model inputs. This was the "
      "reconciliation test that decided the convention, and it is automated "
      "(`goal_convention_reconcile_2025_26` in `outputs/qa/data-validation.json`).\n")
    a(f"Because a tie after 60 minutes is resolved in overtime or a shootout, "
      f"{r26['ot_games']} OT games and {r26['so_games']} SO games are all tied after regulation "
      f"({r26['tied_after_reg']} games in total). Those games are what make the overtime/"
      "shootout submodel estimable from observed behaviour rather than from an assumption.\n")

    # ---------------------------------------------------------------- A
    a("## 4. Dataset A — Dallas 2025-26 team totals\n")
    a(f"One row, complete (82 games). Canonical file: `data/processed/"
      f"team_totals_dal_2025_26.csv`. Fields and values:\n")
    for label, key in [("Games played", "gp"), ("Wins", "wins"), ("Regulation losses", "losses"),
                       ("Overtime/shootout losses", "ot_losses"), ("Points", "points"),
                       ("Point percentage", "point_pct"), ("Goals for", "goals_for"),
                       ("Goals against", "goals_against"), ("Goals for per game", "gf_per_game"),
                       ("Goals against per game", "ga_per_game"),
                       ("Power-play %", "pp_pct"), ("Penalty-kill %", "pk_pct"),
                       ("Shots for per game", "shots_for_per_game"),
                       ("Shots against per game", "shots_against_per_game"),
                       ("Faceoff win %", "faceoff_win_pct"),
                       ("Wins in regulation", "wins_in_regulation"),
                       ("Wins in shootout", "wins_in_shootout"),
                       ("Team shutouts", "team_shutouts")]:
        value = totals26[key]
        shown = f"{value:.4f}" if isinstance(value, float) else value
        a(f"- {label}: **{shown}**")
    a("")
    a("Percentage fields are published as decimals and carry their own numerator and "
      "denominator implicitly: the power-play percentage reconciles against the game log's "
      f"goals-for / opportunities totals in the automated check "
      f"(71 power-play goals on 248 opportunities reproduces the published 0.2863).\n")

    # ---------------------------------------------------------------- B
    a("## 5. Dataset B — Dallas 2025-26 game log\n")
    a(f"82 regular-season rows, one per game, 30 columns. Unique `game_id`, "
      f"`game_type == 2` for every row, no missing mandatory values, home/away split "
      f"{(log26['home_away'] == 'H').sum()}/{(log26['home_away'] == 'A').sum()}.\n")
    a("Fields: game identity and context (`game_id`, `date`, `season`, `opponent`, "
      "`home_away`), regulation/OT/SO goals for and against, the three reconciled totals, "
      "`result` (W/L), `finish` (REG/OT/SO), shots for/against, power-play goals and "
      "opportunities for both teams, faceoff percentage, PIM, hits, blocked shots.\n")
    a("Cleaning performed by code (`collect_game_log`):\n")
    a("1. Keep only `gameType == 2` rows from the season schedule.\n"
      "2. Read period-by-period scoring from the gamecenter linescore, not the box score "
      "score, so regulation goals can be separated from overtime goals.\n"
      "3. Classify each period as REG, OT or SO and sum per side; the shootout column is kept "
      "but never added to a hockey-goal total.\n"
      "4. Take the finishing type from the game outcome period type and cross-check it against "
      "the period arithmetic (an OT game must have exactly one overtime goal).\n"
      "5. Parse power-play strings of the form \"made/opportunities\" into integers.\n")
    a("")
    a("### 5.1 Result and finish distribution\n")
    finish_tbl = (log26.groupby(["finish", "result"]).size().unstack(fill_value=0)
                  .rename(columns={"W": "wins", "L": "losses"}))
    a(_md_table(finish_tbl, index=True))
    a("")
    a("### 5.2 Descriptive summary of the observed games\n")
    quantity_cols = ["goals_for_reg", "goals_against_reg", "goals_for_final_hockey",
                     "goals_against_final_hockey", "shots_for", "shots_against"]
    desc = log26[quantity_cols].describe().T
    desc["variance"] = log26[quantity_cols].var()
    desc = desc.reset_index().rename(columns={"index": "quantity"})
    a(_md_table(desc.round(3), index=False))
    a("")
    a("Artifact: `data/processed/game_log_dal_2025_26.csv`. Per-game raw evidence: "
      f"{len(list((RAW / 'nhl' / 'right_rail').glob('*.json')))} cached `right-rail` JSON files.\n")
    a("![Descriptive view of the 2025-26 season](../outputs/figures/fig8_data_overview.png)\n")
    a("_Figure: rolling 10-game regulation scoring for both calibration seasons, and how the "
      "82 games finished. Descriptive only — no simulated values appear in this figure._\n")

    # ---------------------------------------------------------------- C
    a("## 6. Dataset C — Dallas 2025-26 skaters\n")
    a(f"{len(skaters)} skater rows with Dallas-attributed production. Fields: player id and "
      "name, position, team attribution, GP, goals, assists, points, shots, shooting %, "
      "power-play goals and points, even-strength goals, overtime goals, game-winning goals, "
      "time on ice per game, faceoff % and plus/minus.\n")
    a("**Traded-player handling.** The stats endpoint is queried with a Dallas team filter, so "
      "each row is the player's Dallas-only contribution; full-season production for players "
      "who arrived from elsewhere is stored separately in "
      "`data/processed/arrivals_dal_2026_27_prior_season.csv` (all-team rows). This is the "
      "distinction the proposal requires and it is enforced by an automated check "
      "(`traded_player_attribution`).\n")
    a(_md_table(skaters[["player", "position", "gp", "goals", "assists", "points", "shots",
                         "shooting_pct", "pp_goals", "toi_per_gp_min"]].head(12)))
    a("")
    a(f"Skater goals sum to {int(skaters['goals'].sum())} against a team total of "
      f"{int(totals26['goals_for'])}; the {int(totals26['goals_for']) - int(skaters['goals'].sum())} "
      "goal difference is accounted for by players who left the roster before the snapshot "
      "and did not appear in the team-filtered response. Recorded, not smoothed.\n")

    # ---------------------------------------------------------------- D
    a("## 7. Dataset D — Dallas 2025-26 goalies\n")
    a(f"{len(goalies)} goalie rows. Fields: GP, games started, W/L/OTL, shots against, saves, "
      "goals against, save %, GAA, shutouts.\n")
    a(_md_table(goalies[["player", "gp", "games_started", "wins", "losses", "ot_losses",
                         "shots_against", "saves", "goals_against", "save_pct", "gaa",
                         "shutouts"]]))
    a("")
    a("**Why goalie games and team games are not interchangeable.** "
      f"Goalie appearances sum to {int(goalies['gp'].sum())} against 82 team games, and goalie "
      f"goals against sum to {int(goalies['goals_against'].sum())} against a team total of "
      f"{int(totals26['goals_against'])}. The gap of "
      f"{int(totals26['goals_against']) - int(goalies['goals_against'].sum())} goals equals the "
      f"same-sized gap between goalie shots against ({int(goalies['shots_against'].sum())}) and "
      f"team shots against ({int(log26['shots_against'].sum())}): those are empty-net goals, "
      "which count against the team but not against a goalie. The automated check requires both "
      "gaps to agree, rather than assuming goalie totals must equal team totals.\n")

    # ---------------------------------------------------------------- E
    a("## 8. Dataset E — Dallas 2024-25 season (backtest calibration only)\n")
    a(f"Team totals plus an 82-row game log with the same fields and the same conventions as "
      f"dataset B: `data/processed/team_totals_dal_2024_25.csv`, "
      f"`data/processed/game_log_dal_2024_25.csv`.\n")
    a(f"- Official totals: {r25['official_gf']} GF, {r25['official_ga']} GA, "
      f"{r25['wins']}-{r25['regl']}-{r25['otl']}, {r25['official_points']} points")
    a(f"- Game log reproduces those totals: {r25['log_gf_final']} GF / {r25['log_ga_final']} GA, "
      f"2W+OTL = {r25['log_points']} points")
    a(f"- Tied after regulation: {r25['tied_after_reg']} games ({r25['ot_games']} OT, "
      f"{r25['so_games']} SO)")
    a("")
    a("This season is used **only** to fit the frozen backtest model. It is never used to "
      "calibrate the 2026-27 forecast.\n")

    # ---------------------------------------------------------------- F
    a("## 9. Dataset F — Central Division standings, 2021-22 to 2025-26\n")
    a(f"{len(standings)} team-season rows = 8 Central teams x 5 seasons. Each row is the "
      "standing on that season's final regular-season date (the date is recorded in "
      "`as_of_date`). Fields: season, team, games played, W/L/OTL, points, point %, goals "
      "for/against, division/conference/league rank, clinch indicator and a derived "
      "`made_playoffs` flag.\n")
    a(_md_table(standings[standings["season"] == "2025-26"][
        ["season", "team", "gp", "wins", "losses", "ot_losses", "points", "point_pct",
         "goals_for", "goals_against", "division_rank", "made_playoffs"]], index=False))
    a("")
    a("Point totals for every team-season satisfy `points = 2*W + OTL`; ranks 1-8 are unique "
      "within each season. A small number of teams have 81 games played in the recorded "
      "standings (postponed games whose final standing was frozen); these rows are recorded "
      "as published rather than altered, and the affected seasons are listed in "
      "`standings_games_played` in the validation artifact.\n")
    a("Third-place point totals by season (the threshold statistic):\n")
    a(_md_table(standings[standings.division_rank == 3][
        ["season", "team", "points", "point_pct"]], index=False))
    a("")

    # ---------------------------------------------------------------- G
    a("## 10. Dataset G — Initial 2026-27 Dallas roster (scenario context only)\n")
    a(f"{len(roster)} players from the official roster endpoint "
      f"(snapshot {roster['roster_snapshot_utc'].iloc[0]}): "
      f"{(roster['position_group'] == 'F').sum()} forwards, "
      f"{(roster['position_group'] == 'D').sum()} defensemen, "
      f"{(roster['position_group'] == 'G').sum()} goalies. Fields: player id, name, position "
      "group and code, sweater number, handedness, height, weight, birth date, snapshot "
      "timestamp, source URL.\n")
    a("Arrivals who were not Dallas skaters in 2025-26, with their full-season 2025-26 "
      "production (needed for the roster scenarios):\n")
    a(_md_table(arrivals[["player", "team_attribution", "gp", "goals", "assists", "points",
                          "shooting_pct", "toi_per_gp_min"]], index=False))
    a("")
    a("A roster snapshot is not a lineup and not a transaction log. It supports the two "
      "personnel scenarios and nothing else; no 2026-27 game result exists in any dataset "
      "(checked by `no_2026_27_fitting_data`).\n")

    # ---------------------------------------------------------------- reconciliation
    a("## 11. Reconciliation: observed vs cleaned, and pass/fail evidence\n")
    a("| Quantity | Official source | Cleaned game log | Difference | Verdict |")
    a("|---|---|---|---|---|")
    a(f"| 2025-26 goals for | {r26['official_gf']} | {r26['log_gf_final']} (final hockey) | "
      f"{r26['log_gf_final'] - r26['official_gf']} | PASS |")
    a(f"| 2025-26 goals against | {r26['official_ga']} | {r26['log_ga_final']} (final hockey) | "
      f"{r26['log_ga_final'] - r26['official_ga']} | PASS |")
    a(f"| 2025-26 points | {r26['official_points']} | {r26['log_points']} (2W+OTL) | "
      f"{r26['log_points'] - r26['official_points']} | PASS |")
    a(f"| 2025-26 record | {r26['wins']}-{r26['regl']}-{r26['otl']} | "
      f"{r26['wins']}-{r26['regl']}-{r26['otl']} | 0-0-0 | PASS |")
    a(f"| 2025-26 games | {r26['official_games']} | {r26['log_games']} | "
      f"{r26['log_games'] - r26['official_games']} | PASS |")
    a(f"| Shots for (per game x 82) | {totals26['shots_for_per_game'] * 82:.0f} | "
      f"{int(log26['shots_for'].sum())} | "
      f"{int(log26['shots_for'].sum()) - totals26['shots_for_per_game'] * 82:.0f} | PASS |")
    a(f"| Shots against (per game x 82) | {totals26['shots_against_per_game'] * 82:.0f} | "
      f"{int(log26['shots_against'].sum())} | "
      f"{int(log26['shots_against'].sum()) - totals26['shots_against_per_game'] * 82:.0f} | PASS |")
    a(f"| Power-play % | {totals26['pp_pct']:.4f} | "
      f"{log26['pp_goals_for'].sum() / log26['pp_opps_for'].sum():.4f} | <0.005 | PASS |")
    a(f"| Goalie GA vs team GA | {int(totals26['goals_against'])} | "
      f"{int(goalies['goals_against'].sum())} | "
      f"{int(goalies['goals_against'].sum()) - int(totals26['goals_against'])} "
      f"(empty net; matches the SA gap) | PASS |")
    a(f"| 2024-25 goals for / against | {r25['official_gf']} / {r25['official_ga']} | "
      f"{r25['log_gf_final']} / {r25['log_ga_final']} | 0 / 0 | PASS |")
    a("")
    a("### 11.1 Cross-source check against Hockey-Reference\n")
    a(f"- 2025-26: Hockey-Reference game-log totals **{hr26['hr_sum_GF']:.0f} GF / "
      f"{hr26['hr_sum_GA']:.0f} GA** over {hr26['hr_rows']} games. These equal our *displayed* "
      f"sums ({hr26['log_sum_GF_displayed']:.0f} / {hr26['log_sum_GA_displayed']:.0f}) exactly. "
      "Hockey-Reference prints box-score scores, which include the shootout increment, so the "
      "comparison is made against the like-for-like convention rather than against the "
      "official NHL total.")
    a(f"- 2024-25: Hockey-Reference {hr25['hr_sum_GF']:.0f} GF / {hr25['hr_sum_GA']:.0f} GA over "
      f"{hr25['hr_rows']} games, matching our displayed sums "
      f"({hr25['log_sum_GF_displayed']:.0f} / {hr25['log_sum_GA_displayed']:.0f}).")
    a("- Evidence: `data/processed/hr_crosscheck_2025_26.json`, "
      "`data/processed/hr_crosscheck_2024_25.json`; automated check "
      "`cross_source_gamelog_reconcile`.\n")
    a("### 11.2 Unresolved or approximate items\n")
    a("- Central Division tables are recorded from a standings snapshot on each season's final "
      "date. A handful of clubs show 81 games played; no attempt was made to reconstruct their "
      "postponed fixtures, and the point totals are used as published.")
    a("- The 2026-27 roster is a snapshot, not an opening-night roster, and no transaction-level "
      "arrival/departure dates were collected. Personnel scenarios therefore describe "
      "*roster composition*, not a sequence of dated signings.")
    a("- No advanced five-on-five, expected-goals or injury datasets were collected. They were "
      "optional in the data plan, are not used by the model, and are recorded here as "
      "deliberately out of scope rather than missing.\n")

    # ---------------------------------------------------------------- checklist
    a("## 12. Data-completeness checklist (A-G)\n")
    a("| Dataset | Status | Rows | Artifact | Exception / note |")
    a("|---|---|---|---|---|")
    a(f"| A — 2025-26 team totals | Complete | 1 | `data/processed/team_totals_dal_2025_26.csv` "
      f"| All listed fields present. |")
    a(f"| B — 2025-26 game log | Complete | {len(log26)} | "
      f"`data/processed/game_log_dal_2025_26.csv` | PP and shots reconciled; advanced 5v5 "
      f"fields not collected (optional). |")
